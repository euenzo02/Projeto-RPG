-- Perfil criado automaticamente para novas contas; dados existentes podem ser inseridos ao salvar perfil.
create or replace function public.is_campaign_member(p_campaign uuid)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from campanhas c where c.id=p_campaign and c.mestre_id=auth.uid())
 or exists(select 1 from participantes p where p.campanha_id=p_campaign and p.usuario_id=auth.uid());
$$;
create or replace function public.can_manage_campaign(p_campaign uuid)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from campanhas c where c.id=p_campaign and c.mestre_id=auth.uid())
 or exists(select 1 from participantes p where p.campanha_id=p_campaign and p.usuario_id=auth.uid() and p.pode_gerenciar);
$$;
create or replace function public.is_campaign_gm(p_campaign uuid)
returns boolean language sql stable security definer set search_path=public as $$
 select public.can_manage_campaign(p_campaign);
$$;

