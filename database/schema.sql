-- Recursos compartilhados: mestre/auxiliar gerencia; jogadores leem.
do $$ declare t text; begin
 foreach t in array array['mapas','missoes','sessoes'] loop
  execute format('create policy %I on public.%I for select to authenticated using(public.is_campaign_member(campanha_id))',t||'_read',t);
  execute format('create policy %I on public.%I for all to authenticated using(public.can_manage_campaign(campanha_id)) with check(public.can_manage_campaign(campanha_id))',t||'_manage',t);
 end loop;
end $$;

-- Inventario: jogador acessa seus proprios itens; mestre/auxiliar acessa todos.
create policy itens_read on public.itens for select to authenticated using(public.can_manage_campaign(campanha_id) or dono_id=auth.uid());
create policy itens_insert on public.itens for insert to authenticated with check(public.is_campaign_member(campanha_id) and (dono_id=auth.uid() or public.can_manage_campaign(campanha_id)));
create policy itens_update on public.itens for update to authenticated using(public.can_manage_campaign(campanha_id) or dono_id=auth.uid()) with check(public.can_manage_campaign(campanha_id) or dono_id=auth.uid());
create policy itens_delete on public.itens for delete to authenticated using(public.can_manage_campaign(campanha_id) or dono_id=auth.uid());

