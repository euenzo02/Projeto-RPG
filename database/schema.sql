create policy anotacoes_delete on public.anotacoes for delete to authenticated using(usuario_id=auth.uid() and public.is_campaign_member(campanha_id));

-- Funcao segura: HP de outros personagens e ocultado para jogadores comuns.
create or replace function public.listar_personagens_campanha(p_campanha uuid)
returns table(
 id uuid, campanha_id uuid, usuario_id uuid, nome varchar, conceito text, classe varchar,
 nivel integer, historia text, hp_atual integer, hp_maximo integer, defesa integer,
 condicoes text, criado_em timestamptz, eh_meu boolean
) language sql stable security definer set search_path=public as $$
 select p.id,p.campanha_id,p.usuario_id,p.nome,p.conceito,p.classe,p.nivel,p.historia,
 case when public.can_manage_campaign(p.campanha_id) or p.usuario_id=auth.uid() then p.hp_atual else null end,
 case when public.can_manage_campaign(p.campanha_id) or p.usuario_id=auth.uid() then p.hp_maximo else null end,
 case when public.can_manage_campaign(p.campanha_id) or p.usuario_id=auth.uid() then p.defesa else null end,
 case when public.can_manage_campaign(p.campanha_id) or p.usuario_id=auth.uid() then p.condicoes else null end,
 p.criado_em,(p.usuario_id=auth.uid())
 from public.personagens p where p.campanha_id=p_campanha and public.is_campaign_member(p_campanha)
 order by p.criado_em;
$$;
grant execute on function public.listar_personagens_campanha(uuid) to authenticated;

