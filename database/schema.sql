-- Mantem um perfil publico para cada conta, usando o nome informado no cadastro.
create or replace function public.criar_perfil_novo_usuario()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.perfis(usuario_id,nome_exibicao)
 values(new.id,coalesce(nullif(new.raw_user_meta_data->>'nome',''),split_part(coalesce(new.email,'Aventureiro'),'@',1)))
 on conflict(usuario_id) do nothing;
 return new;
end; $$;
drop trigger if exists ao_criar_usuario_perfil on auth.users;
create trigger ao_criar_usuario_perfil after insert on auth.users
for each row execute procedure public.criar_perfil_novo_usuario();

insert into public.perfis(usuario_id,nome_exibicao)
select id,coalesce(nullif(raw_user_meta_data->>'nome',''),split_part(coalesce(email,'Aventureiro'),'@',1))
from auth.users
on conflict(usuario_id) do nothing;

