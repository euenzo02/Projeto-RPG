create policy sistemas_read on public.sistemas for select to anon, authenticated using(ativo);
create policy perfis_read on public.perfis for select to authenticated using(
 usuario_id=auth.uid()
 or exists(select 1 from participantes p where p.usuario_id=perfis.usuario_id and public.is_campaign_member(p.campanha_id))
 or exists(select 1 from campanhas c where c.mestre_id=perfis.usuario_id and public.is_campaign_member(c.id))
);
create policy perfis_insert on public.perfis for insert to authenticated with check(usuario_id=auth.uid());
create policy perfis_update on public.perfis for update to authenticated using(usuario_id=auth.uid()) with check(usuario_id=auth.uid());

