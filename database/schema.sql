create or replace function public.entrar_campanha(p_codigo text)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_campanha uuid;
begin
 if auth.uid() is null then raise exception 'Faça login para entrar em uma campanha.'; end if;
 select id into v_campanha from public.campanhas where upper(codigo_convite)=upper(trim(p_codigo)) and status='ativa';
 if v_campanha is null then raise exception 'Código inválido ou campanha indisponível.'; end if;
 insert into public.participantes(campanha_id,usuario_id) values(v_campanha,auth.uid()) on conflict(campanha_id,usuario_id) do nothing;
 return v_campanha;
end; $$;
grant execute on function public.entrar_campanha(text) to authenticated;
