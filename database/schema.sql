create table public.sistemas (
 id bigint generated by default as identity primary key,
 nome varchar(100) not null unique,
 descricao text default '',
 ativo boolean not null default true,
 criado_em timestamptz not null default now()
);

create table public.perfis (
 usuario_id uuid primary key references auth.users(id) on delete cascade,
 nome_exibicao varchar(80) not null default 'Aventureiro',
 avatar_url text default '',
 atualizado_em timestamptz not null default now()
);

create table public.campanhas (
 id uuid primary key default gen_random_uuid(),
 nome varchar(120) not null,
 descricao text default '',
 sistema_id bigint references public.sistemas(id) on delete set null,
 mestre_id uuid not null references auth.users(id) on delete cascade,
 codigo_convite text not null unique default upper(substr(encode(gen_random_bytes(6),'hex'),1,10)),
 status text not null default 'ativa' check(status in ('ativa','pausada','concluida')),
 criado_em timestamptz not null default now()
);

create table public.participantes (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 usuario_id uuid not null references auth.users(id) on delete cascade,
 papel text not null default 'jogador' check(papel in ('jogador','mestre_auxiliar')),
 pode_gerenciar boolean not null default false,
 entrou_em timestamptz not null default now(),
 unique(campanha_id,usuario_id)
);

create table public.personagens (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 usuario_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
 nome varchar(120) not null,
 conceito text default '',
 classe varchar(80) default '',
 nivel integer not null default 1 check(nivel > 0),
 historia text default '',
 hp_atual integer not null default 10 check(hp_atual >= 0),
 hp_maximo integer not null default 10 check(hp_maximo > 0),
 defesa integer not null default 10,
 condicoes text default '',
 criado_em timestamptz not null default now(),
 check(hp_atual <= hp_maximo)
);

create table public.mapas (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 nome varchar(120) not null,
 descricao text default '',
 imagem_url text default '',
 tipo varchar(60) not null default 'Local',
 criado_em timestamptz not null default now()
);

create table public.missoes (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 titulo varchar(150) not null,
 descricao text default '',
 status text not null default 'pendente' check(status in ('pendente','em_andamento','concluida')),
 recompensa text default '',
 prazo date,
 criado_em timestamptz not null default now()
);

create table public.sessoes (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 titulo varchar(150) not null,
 resumo text default '',
 data_sessao timestamptz,
 numero integer,
 criado_por uuid not null default auth.uid() references auth.users(id),
 criado_em timestamptz not null default now()
);

create table public.itens (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 dono_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 nome varchar(120) not null,
 descricao text default '',
 categoria varchar(60) default 'Geral',
 quantidade integer not null default 1 check(quantidade >= 0),
 equipado boolean not null default false,
 criado_em timestamptz not null default now()
);

create table public.anotacoes (
 id uuid primary key default gen_random_uuid(),
 campanha_id uuid not null references public.campanhas(id) on delete cascade,
 usuario_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 titulo varchar(150) not null,
 conteudo text default '',
 privada boolean not null default true,
 criado_em timestamptz not null default now(),
 atualizado_em timestamptz not null default now()
);

